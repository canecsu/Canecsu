// Helper to get creators by category
export const getCreatorsByCategory = (category: CreatorCategory): Creator[] => {
  return mockCreators.filter((c) => c.category === category);
};

// Helper to get top ranked creators
export const getTopRankedCreators = (limit: number = 5): Creator[] => {
  return [...mockCreators]
    .sort((a, b) => b.rankScore - a.rankScore)
    .slice(0, limit);
};

// Helper to get creators by city
export const getCreatorsByCity = (city: string): Creator[] => {
  return mockCreators.filter(
    (c) => c.city.toLowerCase() === city.toLowerCase()
  );
};

